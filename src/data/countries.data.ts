/**
 * Every country a phone number can belong to, and what it takes to read one.
 *
 * A row is `[ISO 3166-1 code, calling code, shortest national number, longest
 * national number, trunk prefix]`; the trunk prefix is left out where the
 * country has none. It comes from the libphonenumber-js metadata (version
 * 1.12.33) and was written out once, so the site carries no phone library.
 * Calling codes and number lengths change rarely; refresh the table from that
 * metadata when one does.
 *
 * Three changes were made to what the metadata says. Cameroon is 9 digits only,
 * since the old 8-digit numbers are gone. Cameroon also drops a leading `0`: it
 * has no trunk prefix, but people write one out of habit and no number there
 * starts with it. And a `+1` number is always 10 digits: the 7 digits Canada
 * also lists are a local call, with no area code.
 *
 * Rows are in calling-code order and, within one code, the country that code
 * mostly means comes first — `+1` is the US, `+44` is Great Britain. Reading a
 * number back from its digits takes the first row that matches.
 *
 * The names are not here. The browser already knows them in the visitor's
 * language (`Intl.DisplayNames`), so there is nothing to translate.
 */
export type CountryRowDto = readonly [
  iso: string,
  dialCode: string,
  minLength: number,
  maxLength: number,
  trunkPrefix?: string,
]

